        b: '#..../#..../####./#...#/#...#/#...#/####.',
        c: '..../..../.###/#.../#.../#.../.###',
        d: '....#/....#/.####/#...#/#...#/#...#/.####',
        e: '...../...../.###./#...#/#####/#..../.###.',
        f: '..##/.#../###./.#../.#../.#../.#..',
        g: '...../...../.####/#...#/#...#/#...#/.####/....#/.###.',
        h: '#..../#..../#.##./##..#/#...#/#...#/#...#',
        i: '#/./#/#/#/#/#',
        j: '..#/.../.##/..#/..#/..#/..#/#.#/.#.',
        k: '#.../#.../#..#/#.#./##../#.#./#..#',
        l: '##/.#/.#/.#/.#/.#/.#',
        m: '...../...../##.#./#.#.#/#.#.#/#.#.#/#.#.#',
        n: '...../...../#.##./##..#/#...#/#...#/#...#',
        o: '...../...../.###./#...#/#...#/#...#/.###.',
